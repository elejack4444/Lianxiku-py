#我想在这里生成的文件的命名直接按后面的数字序列生成

#方案 1：用一段 Python 脚本，直接批量生成 `Pylianxi1.py`、`Pylianxi2.py`…（最简单推荐，完全匹配你的命名）

import os

# 文件夹路径，当前工作目录（就是Lianxiku-py）
folder = os.getcwd()
prefix = "Pylianxi"
start = 5    # 从5开始，因为你已经有1、2、3、4
end = 10     # 你想要生成到几号，可以自己修改

for i in range(start, end + 1):
    filename = f"{prefix}{i}.py"
    fullpath = os.path.join(folder, filename)
    # 创建空文件
    with open(fullpath, "w", encoding="utf-8") as f:
        f.write(f"# Pylianxi{i} 练习文件\n")
print("全部文件生成完成！")

# 方案 2：VSCode 插件方式（点一下自动新建下一号文件）

# 插件：**New File Sequence**
# - 安装后，右键文件夹 → `New Numbered File`
# - 自动识别现有文件名，你现在有 Pylianxi4.py，它会自动推荐 `Pylianxi5.py`
# > 缺点：每次只能新建 1 个，适合少量慢慢增加；一次性批量生成不如上面 python 脚本方便。

#那这些文件都是保存过了吗

# 运行脚本执行 `with open(..., "w")` 的那一刻，文件就已经创建并保存到磁盘了**，不是临时文件，左侧资源管理器里看到的就是实实在在保存在硬盘上的文件。

# 细节说明

# 1. `with open(..., "w")`
# 只要代码执行到这一行，就会**在硬盘上新建文件**，并且写入里面的注释内容，自动保存、关闭文件。不需要你再手动 Ctrl+S。
# 2. 和你手动新建文件的区别手动：新建文件 → 写代码 → 按 `Ctrl+S` 才存到硬盘,脚本创建：代码一跑完，**文件和里面预置的注释直接写入硬盘**，永久存在。
# 3. 注意两点
#     1.文件本体已经保存在 `Lianxiku-py` 文件夹里，关闭 VSCode 再打开，文件还在。
#     2.但是！**文件里面后续你自己写的代码，仍然需要你手动 Ctrl+S 保存**。脚本只负责【生成文件 + 写入初始一行注释】；之后你在里面写代码，改动不会自动保存。

