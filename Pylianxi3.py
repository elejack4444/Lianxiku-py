name_1 = "张三" # 定义一个字符串变量并赋值为“张三”
print("字符串的值为：", name_1) # 输出字符串的值

# name_! = "李四" # 定义一个字符串变量并赋值为“李四”，变量名中包含特殊字符“!”报错了，因为变量名不能包含特殊字符

num = 7 // 3 # 使用整数除法运算符//计算7除以3的商，结果为2
print("7除以3的商为：", num) # 输出7除以3的商

num_1 = 7% 3.0 # 使用取模运算符%计算7除以3的余数，结果为1
print("7除以3的余数为：", num_1) # 输出7除以3的余数
print("7除以3的余数的类型为：", type(num_1)) # 输出7除以3的余数的类型

num_2 = 2 ** 3 # 使用幂运算符**计算2的3次方，结果为8
print("2的3次方为：", num_2) # 输出2的3次方
